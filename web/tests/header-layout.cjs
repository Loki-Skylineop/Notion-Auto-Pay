const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const ts = require('typescript')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const source = fs.readFileSync(path.join(__dirname, '../src/App.tsx'), 'utf8')
const ast = ts.createSourceFile('App.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
const declarations = ast.statements.filter(n => ts.isFunctionDeclaration(n) && ['Hero', 'TabBar', 'Stat'].includes(n.name?.text))
assert.equal(declarations.length, 3)
const compiled = ts.transpileModule(declarations.map(n => n.getText(ast)).join('\n') + '\nexports.Hero = Hero', { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS } }).outputText
const exportsObject = {}
new Function('require', 'exports', 'TAB_LABELS', 'IconChevron', 'IconPlus', 'IconLogOut', 'HERO_GLOW', compiled)(require, exportsObject, {pay:'Payment', chat:'Chat', api:'API', mcp:'MCP', users:'Users'}, () => React.createElement('svg'), () => null, () => null, {})
const props = {onAdd:()=>{}, onLogout:()=>{}, accountCount:2, spaceCount:3, tab:'chat', onTab:()=>{}, tabs:['pay','chat','api','mcp','users'], canAdd:true, onToggleCollapse:()=>{}}
const collapsed = renderToStaticMarkup(React.createElement(exportsObject.Hero, {...props, collapsed:true}))
assert.equal((collapsed.match(/<button/g)||[]).length, 1, 'Only the restore arrow remains collapsed')
assert(collapsed.includes('aria-expanded="false"'))
for (const label of ['Payment','Chat','API','MCP','Users']) assert(!collapsed.includes(label), 'Collapsed tab remains visible: '+label)
const expanded = renderToStaticMarkup(React.createElement(exportsObject.Hero, {...props, collapsed:false}))
assert(expanded.includes('aria-expanded="true"'))
for (const label of ['Payment','Chat','API','MCP','Users']) assert(expanded.includes(label))
assert(source.includes("'h-dvh min-h-0 flex flex-col overflow-hidden'"))
assert(source.includes('className="h-full min-h-0"'))
const parts = fs.readFileSync(path.join(__dirname, '../src/components/ChatTabParts.tsx'), 'utf8')
assert(parts.includes("{ height: '100%', minHeight: 0 }"))
assert(!parts.includes('100dvh - 168px'))
console.log('Header collapse hides every action/tab; restore arrow and viewport-filling chat: PASS')
