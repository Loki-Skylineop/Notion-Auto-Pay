const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const ts = require('typescript')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
const source = fs.readFileSync(path.join(__dirname, '../src/components/ChatTabParts.tsx'), 'utf8')
const ast = ts.createSourceFile('parts.tsx', source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
const names = ['StepRow', 'isInternalTool', 'visibleSteps', 'stepCountWord', 'StepsTree', 'StepsBlock', 'StreamingRow', 'renderInline', 'renderBlocks', 'splitTableRow', 'isTableSeparator', 'CodeBlock', 'MessageBody', 'stripEditReferences']
const declarations = ast.statements.filter(n => ts.isFunctionDeclaration(n) && names.includes(n.name?.text))
assert.equal(declarations.length, names.length)
const compiled = ts.transpileModule(declarations.map(n => n.getText(ast)).join('\n'), { compilerOptions: { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.CommonJS } }).outputText
const exported = {}
new Function('require', 'exports', 'useState', 'useCallback', 'CopyIcon', 'ToolIcon', 'DetailBox', 'dotDelay0', 'dotDelay1', 'dotDelay2', compiled)(require, exported, React.useState, React.useCallback, () => null, () => null, () => null, {}, {}, {})
const render = (name, props) => renderToStaticMarkup(React.createElement(exported[name], props))
const steps = ['W: список инструментов', 'W / Grep', 'W / PowerShell', 'W / FileSystem', 'W / Edit', 'W / Grep', 'W / runTool'].map(tool => ({ kind: 'tool', tool, input: '{}' }))
const html = render('StreamingRow', { status: { label: 'Использую инструмент W / runTool', kind: 'tool' }, steps, liveText: '' })
assert(html.indexOf('7 шагов') >= 0 && html.indexOf('7 шагов') < html.indexOf('Использую инструмент'), 'history must be above live status')
assert(!html.includes('W /') && !html.includes('W:'))
assert.match(html, /role="status"[^>]*>Использую инструмент<\/div>/)
assert(!render('StepsBlock', { steps }).includes('W /'), 'history must start collapsed')
const expanded = render('StepsBlock', { steps, defaultOpen: true })
for (const tool of steps) assert(expanded.includes(tool.tool), 'tool lost from expandable history')
const live = render('StreamingRow', { status: { label: 'Думаю…' }, steps, liveText: String.raw`\[Cheburcheck\](https://cheburcheck.ru/)\[\^call_live\]` })
assert.match(live, /href="https:\/\/cheburcheck.ru\/"/)
assert(!live.includes('call_live'))
assert(live.includes('Печатает…'))
const thinking = render('StreamingRow', { status: null, steps: [], liveText: '' })
assert(thinking.includes('Думаю…') && !thinking.includes('шагов'))
console.log('Production chat components: collapsed history above status, expandable tools, streaming links/citations: PASS')
